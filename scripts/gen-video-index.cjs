// Writes src/data/exercise-video.ts from assets/exercises-video/manifest.json: one bundled video per
// exercise with its credit line. Exercises not listed fall back to their still images.
// Run after adding or changing videos: node scripts/gen-video-index.cjs
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'exercises-video');
const manifestPath = path.join(dir, 'manifest.json');
const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : {};
const ids = Object.keys(manifest).sort();
for (const id of ids) {
  if (!fs.existsSync(path.join(dir, manifest[id].file))) throw new Error(`missing video file for ${id}: ${manifest[id].file}`);
}
const key = (id) => (/^[a-z_][a-z0-9_]*$/.test(id) ? id : JSON.stringify(id));
const lines = [
  '// Generated by scripts/gen-video-index.cjs from assets/exercises-video/manifest.json. Do not edit.',
  '// Bundled exercise videos (muted, looping). Licences: src/data/asset-licences.md.',
  'export type BundledVideo = { source: number; credit: string };',
  '',
  'export const EXERCISE_VIDEO: Record<string, BundledVideo> = {',
  ...ids.map((id) => `  ${key(id)}: { source: require('../../assets/exercises-video/${manifest[id].file}'), credit: ${JSON.stringify(manifest[id].credit)} },`),
  '};',
  '',
];
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'exercise-video.ts'), lines.join('\n'));
console.log(ids.length, 'videos');
