"""Write src/data/exercise-3d.ts: the clay images the app shows on the How to tab.

  python render/app_images.py

Uses every exercise that passed the render check (render/review/report.json, the merged render report) minus the ones under
review ("fix") or rejected in render/review/decisions.json. Everything else keeps its
free-exercise-db photo.
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')


def main():
    ok, failed = set(), {}
    for r in glob.glob(os.path.join(HERE, 'review', 'report.json')):
        d = json.load(open(r))
        ok |= set(d['ok'])
        failed.update(d['failed'])
    dec = json.load(open(os.path.join(HERE, 'review', 'decisions.json')))
    hold = set(dec['fix']) | set(dec['rejected'])
    use = sorted(i for i in ok - hold - set(failed)
                 if all(os.path.exists(os.path.join(ROOT, 'assets', 'exercises-3d', f'{i}-{f}.webp')) for f in ('start', 'end')))
    lines = [
        '// Generated by render/app_images.py. Do not edit by hand.',
        '// Clay renders made in Blender from the MakeHuman CC0 body; see src/data/asset-licences.md.',
        '',
        "import type { HowToImages } from './exercise-images';",
        '',
        'export const EXERCISE_3D: Record<string, HowToImages> = {',
    ]
    for i in use:
        lines.append(f"  {i}: {{ start: require('../../assets/exercises-3d/{i}-start.webp'), end: require('../../assets/exercises-3d/{i}-end.webp'), source: 'clay' }},")
    lines += ['};', '']
    open(os.path.join(ROOT, 'src', 'data', 'exercise-3d.ts'), 'w').write('\n'.join(lines))
    print(len(use), 'clay; photos kept for:', ', '.join(sorted(hold | set(failed))))


if __name__ == '__main__':
    main()
